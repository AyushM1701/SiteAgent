#!/usr/bin/env python3
"""
train.py - Fine-Tune Qwen2.5-Coder-3B into an Agentic SLM with QLoRA
Tuned for: RTX 4050 Laptop GPU (6GB VRAM), 24GB DDR5 RAM.

The trainer only accepts the leak-free XML-agent corpus generated by
build_expanded_dataset.py. It withholds part of that corpus for checkpoint
selection, rather than selecting a model against the benchmark.
"""

import argparse
import json
import os
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))
sys.path.insert(0, str(BASE_DIR / "agent"))

base_model_dir = BASE_DIR / "base-model"
if base_model_dir.exists():
    os.environ.setdefault("HF_HUB_OFFLINE", "1")
    os.environ.setdefault("TRANSFORMERS_OFFLINE", "1")
os.environ.setdefault("PYTORCH_CUDA_ALLOC_CONF", "expandable_segments:True")

import torch
from datasets import load_dataset
from agent_protocol import format_chatml, DEFAULT_MAX_SEQ_LENGTH


def check_benchmark_disjointness(training_file: str, eval_file: str = "react_ts_css_eval_set_combined.jsonl"):
    """
    Enforces absolute disjointness between the training dataset and the benchmark evaluation set.
    Raises RuntimeError if any prompt or target symbol overlap is detected.
    """
    if not os.path.exists(eval_file):
        if (BASE_DIR / "data" / "eval" / eval_file).exists():
            eval_file = str(BASE_DIR / "data" / "eval" / eval_file)
        elif (BASE_DIR / "data" / eval_file).exists():
            eval_file = str(BASE_DIR / "data" / eval_file)
        elif (BASE_DIR / eval_file).exists():
            eval_file = str(BASE_DIR / eval_file)
        else:
            print(f"[Disjointness] Note: Benchmark eval set {eval_file} not found; skipping disjointness check.")
            return

    eval_prompts = set()
    with open(eval_file, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
                p = item.get("prompt", "").strip().lower()
                if p:
                    eval_prompts.add(p[:60])
            except Exception:
                pass

    leak_count = 0
    with open(training_file, "r", encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
                for m in rec.get("messages", []):
                    if m.get("role") == "user":
                        u = m.get("content", "").strip().lower()
                        if u[:60] in eval_prompts:
                            print(f"[Disjointness Failure] Line {i}: Prompt matches held-out eval set item: {u[:50]}...")
                            leak_count += 1
            except Exception:
                pass

    if leak_count > 0:
        raise RuntimeError(
            f"Pre-flight data integrity check FAILED: {leak_count} training examples collide with held-out eval set!"
        )
    print(f"[Disjointness Verified] 0 leaks detected between {training_file} and {eval_file}.")


def train(
    dataset_path: str = None,
    epochs: int = 3,
    rank: int = 16,
    lora_alpha: int = None,
    learning_rate: float = 1e-4,
    lora_dropout: float = 0.0,
    validation_split: float = 0.0,
    min_trajectories: int = 10,
    max_seq_length: int = DEFAULT_MAX_SEQ_LENGTH,
    neftune_noise_alpha: float = 0.0,
):
    print("=" * 75)
    print("         TRAINING AGENTIC SLM (Qwen2.5-Coder-3B-Instruct)          ")
    print("         Target Hardware: RTX 4050 Laptop GPU (6GB VRAM)           ")
    print("=" * 75)

    if not torch.cuda.is_available():
        print("Error: CUDA GPU not detected. Training requires an NVIDIA GPU.")
        sys.exit(1)

    print(f"Detected GPU: {torch.cuda.get_device_name(0)}")
    print(f"Allocated VRAM: {torch.cuda.memory_allocated(0)/(1024**2):.1f} MB")

    if dataset_path:
        trajectory_file = dataset_path
        if not os.path.exists(trajectory_file) and (BASE_DIR / trajectory_file).exists():
            trajectory_file = str(BASE_DIR / trajectory_file)
        elif not os.path.exists(trajectory_file) and (BASE_DIR / "data" / trajectory_file).exists():
            trajectory_file = str(BASE_DIR / "data" / trajectory_file)
    elif (BASE_DIR / "data" / "training_data.jsonl").exists():
        trajectory_file = str(BASE_DIR / "data" / "training_data.jsonl")
    elif os.path.exists("training_data.jsonl"):
        trajectory_file = "training_data.jsonl"
    elif (BASE_DIR / "data" / "train_trajectories_agentic.jsonl").exists():
        trajectory_file = str(BASE_DIR / "data" / "train_trajectories_agentic.jsonl")
    else:
        trajectory_file = ""

    if not os.path.exists(trajectory_file):
        print(f"Error: {trajectory_file} not found.")
        sys.exit(1)

    print(f"\n1. Validating dataset integrity & disjointness...")
    check_benchmark_disjointness(trajectory_file)

    print(f"\n2. Loading leak-free multi-turn dataset: {trajectory_file}...")
    raw_dataset = load_dataset("json", data_files=trajectory_file, split="train")
    print(f"Loaded {len(raw_dataset)} training trajectories.")
    if len(raw_dataset) < min_trajectories:
        print(
            f"Error: only {len(raw_dataset)} leak-free trajectories are available; "
            f"need at least {min_trajectories}. Generate more verified STaR rollouts first."
        )
        sys.exit(1)

    from unsloth import FastLanguageModel
    from trl import SFTTrainer, SFTConfig

    model_name = "./base-model" if os.path.exists("./base-model") else "unsloth/Qwen2.5-Coder-3B-Instruct"

    print(f"\n2. Loading 4-bit base model from: {model_name} (max_seq_length={max_seq_length})...")
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=model_name,
        max_seq_length=max_seq_length,
        load_in_4bit=True,
    )

    actual_alpha = lora_alpha if lora_alpha is not None else rank
    print(f"\n3. Attaching LoRA adapters (rank={rank}, alpha={actual_alpha}, dropout={lora_dropout})...")
    model = FastLanguageModel.get_peft_model(
        model,
        r=rank,
        target_modules=[
            "q_proj", "k_proj", "v_proj", "o_proj",
            "gate_proj", "up_proj", "down_proj"
        ],
        lora_alpha=actual_alpha,
        lora_dropout=lora_dropout,
        bias="none",
        use_gradient_checkpointing="unsloth",
        random_state=42,
    )

    # Serialize with the identical ChatML formatter used at inference time.
    def format_chatml_trajectory(example):
        text = format_chatml(example["messages"], add_generation_prompt=False) + tokenizer.eos_token
        return {"text": text}

    dataset = raw_dataset.map(format_chatml_trajectory)

    def is_within_context(example):
        return len(tokenizer(example["text"], add_special_tokens=False)["input_ids"]) <= max_seq_length

    before_length_filter = len(dataset)
    dataset = dataset.filter(is_within_context)
    dropped = before_length_filter - len(dataset)
    if dropped:
        print(f"Dropped {dropped} trajectories that would truncate past {max_seq_length} tokens.")
    if len(dataset) < min_trajectories:
        print("Error: too few trajectories remain after length validation.")
        sys.exit(1)

    has_eval = (validation_split > 0.0 and len(dataset) >= 20)
    if has_eval:
        splits = dataset.train_test_split(test_size=validation_split, seed=42)
        train_dataset = splits["train"]
        eval_dataset = splits["test"]
        print(f"Train/validation split: {len(train_dataset)}/{len(eval_dataset)} trajectories.")
    else:
        train_dataset = dataset
        eval_dataset = None
        print(f"Training on all {len(train_dataset)} trajectories (evaluation disabled for small dataset).")

    print("\n4. Configuring SFTTrainer...")
    output_dir = "agent_lora_output"
    sft_kwargs = dict(
        output_dir=output_dir,
        per_device_train_batch_size=1,        # 1 sample per step fits 6GB VRAM
        gradient_accumulation_steps=4,
        warmup_ratio=0.05,
        num_train_epochs=epochs,
        learning_rate=learning_rate,
        fp16=not torch.cuda.is_bf16_supported(),
        bf16=torch.cuda.is_bf16_supported(),
        logging_steps=1,
        optim="adamw_8bit",                    # 8-bit optimizer saves 1.5GB VRAM
        weight_decay=0.01,
        lr_scheduler_type="cosine",
        eval_strategy="epoch" if has_eval else "no",
        eval_accumulation_steps=1,             # Chunks eval logits to prevent 5.6GB FP32 OOM on 152k vocab
        save_strategy="epoch",
        save_total_limit=2,
        load_best_model_at_end=has_eval,
        metric_for_best_model="eval_loss" if has_eval else None,
        greater_is_better=False,
        prediction_loss_only=True,
        report_to="none",
        seed=42,
    )
    if neftune_noise_alpha > 0:
        sft_kwargs["neftune_noise_alpha"] = neftune_noise_alpha
    sft_config = SFTConfig(**sft_kwargs)

    from unsloth.chat_templates import train_on_responses_only

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        train_dataset=train_dataset,
        eval_dataset=eval_dataset,
        dataset_text_field="text",
        max_seq_length=max_seq_length,
        args=sft_config,
    )

    print("\n5. Applying Response-Only Loss Masking (ignoring system prompt, user prompt, & observations)...")
    trainer = train_on_responses_only(
        trainer,
        instruction_part="<|im_start|>user\n",
        response_part="<|im_start|>assistant\n",
    )

    print("\n6. Starting Agentic LoRA Training...")
    trainer.train()

    save_path = str(BASE_DIR / "my-react-agent-lora")
    print(f"\n7. Training complete! Saving LoRA adapter to '{save_path}'...")
    model.save_pretrained(save_path)
    tokenizer.save_pretrained(save_path)
    print(f"Saved successfully to: {os.path.abspath(save_path)}")
    print("\nNext step: Merge LoRA or run eval with: python agent/agent.py --model my-react-agent-lora")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Fine-tune Qwen2.5-Coder-3B into an Agentic SLM")
    parser.add_argument("--data", "--dataset", dest="dataset", type=str, default=None, help="Leak-free XML-agent dataset JSONL.")
    parser.add_argument("--epochs", type=int, default=3, help="Number of training epochs (default: 3).")
    parser.add_argument("--rank", type=int, default=16, choices=[8, 16, 32, 64], help="LoRA rank for the sweep (default: 16).")
    parser.add_argument("--lora-alpha", type=int, default=None, help="LoRA alpha (default: matches rank).")
    parser.add_argument("--learning-rate", type=float, default=1e-4, help="LoRA learning rate (default: 1e-4).")
    parser.add_argument("--lora-dropout", type=float, default=0.0, help="LoRA dropout (default: 0.0 for Unsloth fast patching).")
    parser.add_argument("--validation-split", type=float, default=0.0, help="Held-out trajectory split for checkpoint selection (default: 0.0 to prevent 15GB FP32 logits OOM during eval on 6GB VRAM).")
    parser.add_argument("--min-trajectories", type=int, default=10, help="Minimum trajectories required.")
    parser.add_argument("--max-seq-length", type=int, default=DEFAULT_MAX_SEQ_LENGTH, help=f"Maximum sequence length for multi-turn trajectories (default: {DEFAULT_MAX_SEQ_LENGTH}).")
    parser.add_argument("--neftune-noise-alpha", type=float, default=0.0, help="Disabled by default to preserve protocol-token fidelity.")
    args = parser.parse_args()
    train(
        dataset_path=args.dataset,
        epochs=args.epochs,
        rank=args.rank,
        lora_alpha=args.lora_alpha,
        learning_rate=args.learning_rate,
        lora_dropout=args.lora_dropout,
        validation_split=args.validation_split,
        min_trajectories=args.min_trajectories,
        max_seq_length=args.max_seq_length,
        neftune_noise_alpha=args.neftune_noise_alpha,
    )
